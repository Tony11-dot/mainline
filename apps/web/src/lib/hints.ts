import { buildGraph, importPgn, INITIAL_FEN, isOwnTurn, lines, playUci, positionFromFen, rootFromMoves, toFen, type Color } from '@mainline/shared';
import { useEffect, useState } from 'react';
import { useI18n } from './i18n';
import { packMoves, type Pack } from './packs';

/**
 * One-line "why this move" hints for the ready-made packs: static data written once from the app's
 * own facts packets (engine lines, explorer statistics, pawn structure), validated move by move, and
 * translated into every app language — nothing is generated at run time. Shown when a move is missed
 * in training. Files: public/data/hints/<lang>.json, regenerated by scripts/hints/.
 */
export const HINTS_VERSION = 1;

/** A hint belongs to a position and the trained move in it; transpositions share one. */
export const hintKey = (epd: string, uci: string) => `${epd} ${uci}`;

export interface HintTarget {
  key: string;
  epd: string;
  /** Full FEN of the position along the first line that reached it. */
  fen: string;
  uci: string;
  san: string;
  color: Color;
  /** Plies from the starting position. */
  ply: number;
  /** UCI moves from the starting position. */
  path: string[];
  /** "<pack>:<line>" of every line that trains this move. */
  sources: string[];
}

/**
 * Every position the packs train: the pack's side to move and the line's main move there, as the
 * trainer sees it (same import, same mainline rule), deduplicated across packs and lines.
 */
export function packHintTargets(packs: readonly Pack[]): HintTarget[] {
  const out = new Map<string, HintTarget>();
  for (const p of packs) {
    const rootMoves = packMoves(p);
    const root = rootFromMoves(rootMoves);
    for (const l of p.lines) {
      const res = importPgn(l.pgn, { id: `${p.id}:${l.id}`, color: p.color, rootEpd: root.epd });
      if (res.errors.length) throw new Error(`${p.id}:${l.id}: ${res.errors.join('; ')}`);
      const g = buildGraph(res.moves);
      for (const line of lines(g, root.epd, { mainlineOnlyFor: p.color })) {
        let pos = positionFromFen(INITIAL_FEN);
        const path: string[] = [];
        const step = (uci: string) => {
          const played = playUci(pos, uci);
          pos = played.pos;
          path.push(played.uci);
        };
        for (const u of rootMoves) step(u);
        for (const m of line.moves) {
          if (isOwnTurn(p.color, m.fromEpd)) {
            const key = hintKey(m.fromEpd, m.uci);
            const e = out.get(key) ?? { key, epd: m.fromEpd, fen: toFen(pos), uci: m.uci, san: m.san, color: p.color, ply: path.length, path: [...path], sources: [] };
            const src = `${p.id}:${l.id}`;
            if (!e.sources.includes(src)) e.sources.push(src);
            out.set(key, e);
          }
          step(m.uci);
        }
      }
    }
  }
  return [...out.values()].sort((a, b) => a.ply - b.ply || a.key.localeCompare(b.key));
}

interface HintFile {
  v: number;
  lang: string;
  hints: Record<string, string>;
}

const tables = new Map<string, Promise<Record<string, string>>>();

/** The hints in one language; a missing or broken file is an empty table. */
export function hintTable(lang: string): Promise<Record<string, string>> {
  let p = tables.get(lang);
  if (!p) {
    p = fetch(`/data/hints/${lang}.json`)
      .then(async (r) => {
        if (!r.ok) throw new Error(`hints ${lang}: ${r.status}`);
        const f = (await r.json()) as HintFile;
        return f.v === HINTS_VERSION && f.hints ? f.hints : {};
      })
      .catch(() => ({}));
    tables.set(lang, p);
  }
  return p;
}

/** The hint for a trained move in the app language, falling back to English when it has none. */
export async function hintFor(epd: string, uci: string, lang = useI18n.getState().lang): Promise<string | undefined> {
  const key = hintKey(epd, uci);
  const own = (await hintTable(lang))[key];
  if (own) return own;
  return lang === 'en' ? undefined : (await hintTable('en'))[key];
}

/** The hint for a trained move, once loaded; undefined while loading or when there is none. */
export function usePackHint(epd: string | undefined, uci: string | undefined): string | undefined {
  const lang = useI18n((s) => s.lang);
  const [hint, setHint] = useState<string>();
  useEffect(() => {
    let live = true;
    setHint(undefined);
    if (!epd || !uci) return;
    void hintFor(epd, uci, lang).then((h) => live && setHint(h));
    return () => {
      live = false;
    };
  }, [epd, uci, lang]);
  return epd && uci ? hint : undefined;
}

/** Test hook. */
export function _resetHintTables() {
  tables.clear();
}
